# Clone a profile for a real three-instance E2E check of the sooyo sync layer.
#
# Why a clone: the desktop profile is owned by the running Electron app, and this project's own
# rule is never to touch desktop's package.json / lockfile / node_modules. A clone installs the
# same bundle from the same path, so `apply()` runs exactly the code under test.
#
# Each instance also gets its OWN `DSH_HOME`. That is the only thing that actually isolates it:
# `storage-json.root` defaults to `dshHomePath('storages')`, an `!!js` expression a patch cannot
# override, so two instances sharing one home would read and write the same database — the check
# would then "pass" by reading the desktop user's real data, and corrupt it on the first write.
#
# Usage:  powershell -NoProfile -ExecutionPolicy Bypass -File dev/e2e-setup.ps1
#         powershell -NoProfile -ExecutionPolicy Bypass -File dev/e2e-teardown.ps1
#
# Layout:  $DSH_HOME\e2e\<instance>\  is that instance's DSH_HOME
#          $DSH_HOME\e2e\<instance>\profiles\<profile>\  is its cloned profile
#
# NB: this file is ASCII only. PowerShell 5.1's `-Encoding ASCII` heredocs would mangle
# non-ASCII characters, and its `-Encoding UTF8` prepends a BOM that DSH's JSON reader rejects.

param(
  [string]$Source = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
$base = Join-Path $env:DSH_HOME 'e2e'
if (Test-Path $base) { Remove-Item -Recurse -Force $base }

# The roles and their ports. The Hub is authoritative; the two clients only proxy.
$profiles = @(
  @{ instance = 'hub'; profile = 'sooyo-hub'; role = 'hub';    port = 3101; device = 'hub-server'; token = $null },
  @{ instance = 'a';   profile = 'sooyo-a';   role = 'client'; port = 3102; device = 'device-a';   token = 'e2e-hub-write-token-0123456789' },
  @{ instance = 'b';   profile = 'sooyo-b';   role = 'client'; port = 3103; device = 'device-b';   token = 'e2e-hub-read-token-0123456789' }
)

foreach ($entry in $profiles) {
  $instanceHome = Join-Path $base $entry.instance
  $dir = Join-Path (Join-Path $instanceHome 'profiles') $entry.profile
  New-Item -ItemType Directory -Force -Path $dir | Out-Null

  # A minimal but complete profile: an empty cordis.yml (the tree is composed from patches), a
  # workspace file, a package.json that depends on this working tree, and the patch rows.
  # Deliberately NOT a copy of the web profile: that would install twelve unrelated plugins.
  Set-Content -Path (Join-Path $dir 'cordis.yml') -Encoding ASCII -Value @'
# dsh profile root - composed from package.json dsh.profile.bundles + cordis.patch.yml.
[]
'@

  Set-Content -Path (Join-Path $dir 'pnpm-workspace.yaml') -Encoding ASCII -Value @'
packages:
  - .

nodeLinker: hoisted
autoInstallPeers: false
'@

  # `link:` is what `plugin_manager install_bundle` produces for a local directory, so the
  # Loader resolves the bundle exactly as it does in production.
  $package = [ordered]@{
    name         = "dsh-profile-$($entry.profile)"
    private      = $true
    dependencies = [ordered]@{ 'dsh-sooyo' = "link:$($Source -replace '\\', '/')" }
    dsh          = [ordered]@{
      profile = [ordered]@{
        bundles         = @('@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app', 'dsh-sooyo')
        disabledBundles = @()
      }
    }
  }
  $package | ConvertTo-Json -Depth 8 | Set-Content -Path (Join-Path $dir 'package.json') -Encoding UTF8

  $sync = if ($entry.role -eq 'hub') {
    @'
          role: hub
          device: hub-server
          allowLoopbackOnly: true
          tokens:
            - { token: 'e2e-hub-write-token-0123456789', device: device-a, access: write }
            - { token: 'e2e-hub-read-token-0123456789', device: device-b, access: read }
'@
  } else {
    @"
          role: client
          device: $($entry.device)
          endpoint: http://127.0.0.1:3101
          token: '$($entry.token)'
          cacheMs: 0
"@
  }

  Set-Content -Path (Join-Path $dir 'cordis.patch.yml') -Encoding ASCII -Value @"
# Generated by dev/e2e-setup.ps1 - not for commit.
- insert:
    - id: sooyo
      name: dsh-sooyo
      config:
        mode: selected
        sync:
$sync
"@

  # Strip the BOM from every generated file: PowerShell 5.1's `-Encoding UTF8` always adds one,
  # and DSH's JSON reader treats it as content (`Unexpected token '`).
  foreach ($file in @('package.json', 'cordis.yml', 'pnpm-workspace.yaml', 'cordis.patch.yml')) {
    $path = Join-Path $dir $file
    if (-not (Test-Path $path)) { continue }
    $text = [System.IO.File]::ReadAllText($path)
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
  }

  Write-Host "created $dir"
  Write-Host "  DSH_HOME=$instanceHome  role=$($entry.role)  port=$($entry.port)"
}

Write-Host ''
Write-Host 'Next: install and boot each instance with its own DSH_HOME.'
foreach ($entry in $profiles) {
  $instanceHome = Join-Path $base $entry.instance
  Write-Host "  `$env:DSH_HOME='$instanceHome'; dsh plugin --profile $($entry.profile) install"
  Write-Host "  `$env:DSH_HOME='$instanceHome'; dsh --profile $($entry.profile) --port $($entry.port) --no-open"
}
Write-Host ''
Write-Host 'Then: powershell -NoProfile -ExecutionPolicy Bypass -File dev/e2e-verify.ps1'
